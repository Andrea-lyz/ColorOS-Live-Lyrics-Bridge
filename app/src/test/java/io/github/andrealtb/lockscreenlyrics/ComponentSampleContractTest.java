    private interface Check {
        String run() throws Throwable;
    }

    private static String outcome(Check check) {
        try {
            return check.run();
        } catch (Throwable t) {
            return "FAIL " + simple(t);
        }
    }

    private static String simple(Throwable t) {
        if (t == null) return "unknown";
        String message = t.getMessage();
        if (message != null) {
            // Keep simple type names only; the summary already pins the full identity.
            message = message.replaceAll("(?:[A-Za-z_][\\w]*\\.)+([A-Za-z_$][\\w$]*)", "$1");
            if (message.length() > 100) message = message.substring(0, 100);
        }
        return t.getClass().getSimpleName() + (message == null ? "" : ": " + message);
    }

    private static String optional(String label, Object value) {
        return label + "=" + (value != null ? "yes" : "no");
    }

    /** DexKit anyOf over the anchor sets of one group, then exactly one class. */
    private static Class<?> single(JSONObject sample, ClassLoader loader, String group)
            throws ReflectiveOperationException {
        try {
            return singleChecked(sample, loader, group);
        } catch (ReflectiveOperationException | RuntimeException e) {
            throw e;
        } catch (Exception e) {
            throw new IllegalStateException(e);
        }
    }

    private static Class<?> singleChecked(JSONObject sample, ClassLoader loader, String group) throws Exception {
        JSONArray specAnchors = sample.getJSONObject("anchorSpec").getJSONArray("anchors");
        Set<String> hits = new LinkedHashSet<>();
        for (int i = 0; i < specAnchors.length(); i++) {
            JSONObject anchor = specAnchors.getJSONObject(i);
            if (!group.equals(anchor.getString("group"))) continue;
            JSONArray classes = sample.getJSONObject("anchors").getJSONArray(anchor.getString("key"));
            for (int j = 0; j < classes.length(); j++) hits.add(classes.getString(j));
        }
        if (hits.size() != 1) throw new IllegalStateException("Expected one " + group + ", found " + hits.size());
        return loader.loadClass(binary(hits.iterator().next()));
    }

    private static Method unique(Class<?> owner, String description, Predicate<Method> predicate) {
        Method match = null;
        for (Method method : owner.getDeclaredMethods()) {
            if (!predicate.test(method)) continue;
            if (match != null) throw new IllegalStateException("Expected one " + description);
            match = method;
        }
        if (match == null) throw new IllegalStateException("No " + description);
        return match;
    }

    /** Key-sorted rendering; the org.json on the Android test classpath has no similar(). */
    private static String canonical(Object value) throws Exception {
        if (value instanceof JSONObject) {
            JSONObject o = (JSONObject) value;
            TreeSet<String> keys = new TreeSet<>();
            o.keys().forEachRemaining(keys::add);
            StringBuilder b = new StringBuilder("{");
            for (String k : keys) b.append(JSONObject.quote(k)).append(':').append(canonical(o.get(k))).append(',');
            return b.append('}').toString();
        }
        if (value instanceof JSONArray) {
            JSONArray a = (JSONArray) value;
            StringBuilder b = new StringBuilder("[");
            for (int i = 0; i < a.length(); i++) b.append(canonical(a.get(i))).append(',');
            return b.append(']').toString();
        }
        return value instanceof String ? JSONObject.quote((String) value) : String.valueOf(value);
    }

    private static String binary(String descriptor) {
        return descriptor.substring(1, descriptor.length() - 1).replace('/', '.');
    }

    private static String name(JSONObject sample) throws Exception {
        return sample.getString("component") + " " + sample.getString("versionName") + " "
                + sample.getString("sha256").substring(0, 12) + " (" + sample.getString("label") + ")";
    }

    private static List<JSONObject> samples() throws Exception {
        List<JSONObject> out = new ArrayList<>();
        try (Stream<Path> files = Files.list(resource("samples"))) {
            for (Path p : files.filter(f -> f.toString().endsWith(".json")).sorted().collect(Collectors.toList())) {
                out.add(new JSONObject(read(p)));
            }
        }
        return out;
    }

    private static Path resource(String name) {
        Path p = Paths.get("src/test/resources/compat").resolve(name);
        return Files.exists(p) ? p : Paths.get("app").resolve(p);
    }

    private static Path mainSource() {
        Path p = Paths.get("src/main/java");
        return Files.isDirectory(p) ? p : Paths.get("app").resolve(p);
    }

    private static String read(Path p) throws IOException {
        return new String(Files.readAllBytes(p), StandardCharsets.UTF_8);
    }

    /**
     * Defines the summarized classes from their signatures. Any other type a signature names and
     * the test classpath lacks becomes an empty stub, so reflection over the members resolves.
     */
    static final class SampleLoader extends ClassLoader {
        private final JSONObject classes;

        SampleLoader(JSONObject sample) throws Exception {
            super(ComponentSampleContractTest.class.getClassLoader());
            this.classes = sample.getJSONObject("classes");
        }

        @Override
        protected Class<?> findClass(String name) throws ClassNotFoundException {
            if (name.startsWith("java.")) throw new ClassNotFoundException(name);
            String internal = name.replace('.', '/');
            String descriptor = "L" + internal + ";";
            byte[] bytes;
            try {
                bytes = classes.has(descriptor) ? define(internal, classes.getJSONObject(descriptor))
                        : stub(internal);
            } catch (Exception e) {
                throw new ClassNotFoundException(name, e);
            }
            return defineClass(name, bytes, 0, bytes.length);
        }

        private boolean loadable(String internal) {
            try {
                loadClass(internal.replace('/', '.'));
                return true;
            } catch (ClassNotFoundException | LinkageError e) {
                return false;
            }
        }

        private static byte[] stub(String internal) {
            ClassWriter w = new ClassWriter(0);
            w.visit(Opcodes.V11, Opcodes.ACC_PUBLIC | Opcodes.ACC_SUPER, internal, null, "java/lang/Object", null);
            w.visitEnd();
            return w.toByteArray();
        }

        private byte[] define(String internal, JSONObject c) throws Exception {
            int access = c.getInt("access");
            boolean isInterface = (access & Opcodes.ACC_INTERFACE) != 0;
            int classAccess = access & (Opcodes.ACC_PUBLIC | Opcodes.ACC_FINAL | Opcodes.ACC_INTERFACE
                    | Opcodes.ACC_ABSTRACT | Opcodes.ACC_SYNTHETIC | Opcodes.ACC_ANNOTATION | Opcodes.ACC_ENUM);
            classAccess |= Opcodes.ACC_PUBLIC;
            if (!isInterface) classAccess |= Opcodes.ACC_SUPER;
            String superName = "java/lang/Object";
            if (!c.isNull("super")) {
                String s = c.getString("super");
                String sInternal = s.substring(1, s.length() - 1);
                if (isInterface || loadable(sInternal)) superName = isInterface ? "java/lang/Object" : sInternal;
            }
            List<String> interfaces = new ArrayList<>();
            JSONArray ifaces = c.getJSONArray("interfaces");
            for (int i = 0; i < ifaces.length(); i++) {
                String s = ifaces.getString(i);
                String iInternal = s.substring(1, s.length() - 1);
                try {
                    Class<?> k = loadClass(iInternal.replace('/', '.'));
                    if (k.isInterface()) interfaces.add(iInternal);
                } catch (ClassNotFoundException | LinkageError ignored) {
                    // Unknown interface: dropped, member signatures are what the resolvers read.
                }
            }
            ClassWriter w = new ClassWriter(0);
            w.visit(Opcodes.V11, classAccess, internal, null, superName, interfaces.toArray(new String[0]));
            JSONArray fields = c.getJSONArray("fields");
            for (int i = 0; i < fields.length(); i++) {
                JSONArray f = fields.getJSONArray(i);
                w.visitField(f.getInt(2) & 0xFFFF, f.getString(0), f.getString(1), null, null).visitEnd();
            }
            JSONArray methods = c.getJSONArray("methods");
            for (int i = 0; i < methods.length(); i++) {
                JSONArray m = methods.getJSONArray(i);
                String name = m.getString(0);
                if ("<clinit>".equals(name)) continue;
                StringBuilder desc = new StringBuilder("(");
                JSONArray params = m.getJSONArray(1);
                int slots = 0;
                for (int j = 0; j < params.length(); j++) {
                    String p = params.getString(j);
                    desc.append(p);
                    slots += "J".equals(p) || "D".equals(p) ? 2 : 1;
                }
                desc.append(')').append(m.getString(2));
                int acc = m.getInt(3) & 0xFFFF;
                MethodVisitor mv = w.visitMethod(acc, name, desc.toString(), null, null);
                if ((acc & (Opcodes.ACC_ABSTRACT | Opcodes.ACC_NATIVE)) == 0) {
                    mv.visitCode();
                    mv.visitTypeInsn(Opcodes.NEW, "java/lang/UnsupportedOperationException");
                    mv.visitInsn(Opcodes.DUP);
                    mv.visitMethodInsn(Opcodes.INVOKESPECIAL, "java/lang/UnsupportedOperationException",
                            "<init>", "()V", false);
                    mv.visitInsn(Opcodes.ATHROW);
                    mv.visitMaxs(2, slots + 1);
                }
                mv.visitEnd();
            }
            w.visitEnd();
            return w.toByteArray();
        }
    }
