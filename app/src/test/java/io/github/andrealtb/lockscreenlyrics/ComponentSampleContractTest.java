    private static Map<String, String> systemUiRow(JSONObject sample) throws Exception {
        SampleLoader loader = new SampleLoader(sample);
        Map<String, String> row = new java.util.LinkedHashMap<>();
        String dexKit = outcome(() -> {
            SystemUiDexKitAdapter.Targets t = emulateSystemUiDexKit(sample, loader);
            return "OK rus=" + t.rusVariant + optional(" lyricSupportGate", t.resolveLyricSupport)
                    + optional(" metadataChanged", t.metadataChanged);
        });
        String legacy = outcome(() -> {
            SystemUiDexKitAdapter.Targets t = SystemUiDexKitAdapter.resolveLegacy(loader);
            return "OK rus=" + t.rusVariant + optional(" lyricSupportGate", t.resolveLyricSupport)
                    + optional(" metadataChanged", t.metadataChanged);
        });
        String factory = outcome(() -> {
            Method m = loader.loadClass("com.android.systemui.shared.plugins.PluginInstance$PluginFactory")
                    .getDeclaredMethod("createClassLoader");
            return OplusPluginClassLoaderPolicy.isClassLoaderFactory(m) ? "OK" : "FAIL shape";
        });
        String constructors = outcome(() -> "n=" + loader.loadClass(
                "com.android.systemui.shared.plugins.OPlusPluginClassLoader").getDeclaredConstructors().length);
        // Plugin hooks need either the ColorOS 16 loader constructor or the ColorOS 17 factory.
        boolean pluginLoader = factory.startsWith("OK")
                || (constructors.startsWith("n=") && !"n=0".equals(constructors));
        boolean policy = dexKit.startsWith("OK") || legacy.startsWith("OK");
        row.put("core", policy && pluginLoader ? "OK"
                : "FAIL mediaPolicy=" + policy + " pluginLoader=" + pluginLoader);
        row.put("media-policy.dexkit", dexKit);
        row.put("media-policy.legacy", legacy);
        row.put("plugin-loader.factory", factory);
        row.put("plugin-loader.constructors", constructors);
        row.put("translation-action", outcome(() -> {
            Class<?> ex = loader.loadClass("com.android.systemui.media.controls.models.player.OplusMediaActionEx");
            Constructor<?> exCtor = TranslationToggleMediaActionBinder.resolveActionExConstructor(ex);
            loader.loadClass("com.android.systemui.media.controls.shared.model.MediaAction").getDeclaredConstructor(
                    Drawable.class, Runnable.class, CharSequence.class, Drawable.class, Integer.class, ex);
            return "OK actionEx=" + exCtor.getParameterCount() + "-arg";
        }));
        row.put("aod-media-support", outcome(() -> {
            Class<?> c = loader.loadClass("com.oplusos.systemui.aod.mediapanel.AodMediaDataListener$Companion");
            int n = 0;
            for (String m : new String[] {"isAodMediaSupport", "isAodMediaSupportWithoutFeature"}) {
                try {
                    c.getDeclaredMethod(m, String.class);
                    n++;
                } catch (NoSuchMethodException ignored) {
                    // optional
                }
            }
            return "methods=" + n;
        }));
        return row;
    }

    /** Mirrors SystemUiDexKitAdapter.resolveTargets with the DexKit class search precomputed. */
    private static SystemUiDexKitAdapter.Targets emulateSystemUiDexKit(JSONObject sample, SampleLoader loader)
            throws Exception {
        Class<?> rus = single(sample, loader, "rus-manager");
        Class<?> selector = single(sample, loader, "action-selector");
        Class<?> strategy = single(sample, loader, "action-strategy");
        Class<?> lyricLoader = single(sample, loader, "lyric-loader");
        Class<?> bundle = single(sample, loader, "seedling-bundle");
        Method dealEndTag = unique(rus, "RUS end-tag handler", SystemUiDexKitAdapter::isDealEndTagShape);
        Method save = unique(rus, "RUS persistence", SystemUiDexKitAdapter::isSaveListToSpShape);
        Method whiteList = SystemUiDexKitAdapter.findOptionalMethod(rus, "RUS whitelist getter",
                SystemUiDexKitAdapter::isRusWhiteListGetterShape);
        Method entrance = unique(selector, "lyric entrance", SystemUiDexKitAdapter::isLyricEntranceLookupShape);
        Method gate = SystemUiDexKitAdapter.findOptionalMethod(selector, "lyric support gate",
                SystemUiDexKitAdapter::isLyricSupportGateShape);
        Method rules = unique(selector, "rule update", SystemUiDexKitAdapter::isUpdatePkgActionsRuleShape);
        Method actions = unique(strategy, "media action builder", method -> !Modifier.isStatic(method.getModifiers())
                && method.getReturnType() != void.class
                && method.getParameterCount() == 3
                && method.getParameterTypes()[0] == String.class
                && method.getParameterTypes()[2] == MediaController.class);
        Method load = unique(lyricLoader, "lyricInfo loader", method -> !Modifier.isStatic(method.getModifiers())
                && method.getParameterCount() == 6
                && method.getParameterTypes()[0] == String.class
                && method.getParameterTypes()[1] == MediaMetadata.class
                && method.getParameterTypes()[2] == String.class
                && method.getParameterTypes()[3] == String.class
                && method.getParameterTypes()[4] == String.class
                && method.getReturnType() == method.getParameterTypes()[5]);
        // The DexKit log-string search for metadata-changed is not emulated; this is its fallback.
        Method metadata;
        try {
            metadata = SystemUiDexKitAdapter.findMetadataChangedEntry(lyricLoader);
        } catch (RuntimeException e) {
            metadata = null;
        }
        Method toBundle = unique(bundle, "Seedling media bundle mapper", method -> Modifier.isStatic(method.getModifiers())
                && method.getReturnType() == Bundle.class
                && method.getParameterCount() == 3
                && List.class.isAssignableFrom(method.getParameterTypes()[0])
                && method.getParameterTypes()[1] == boolean.class
                && method.getParameterTypes()[2] == boolean.class);
        return new SystemUiDexKitAdapter.Targets(dealEndTag, save, whiteList, null, entrance, gate, rules,
                actions, load, metadata, toBundle, true,
                whiteList != null ? SystemUiDexKitAdapter.RUS_VARIANT_OLD : SystemUiDexKitAdapter.RUS_VARIANT_NEW);
    }

