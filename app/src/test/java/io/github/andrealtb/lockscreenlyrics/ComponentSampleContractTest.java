    private static Map<String, String> pluginRow(JSONObject sample) throws Exception {
        SampleLoader loader = new SampleLoader(sample);
        Map<String, String> row = new java.util.LinkedHashMap<>();
        String dexKit = outcome(() -> {
            OplusPluginDexKitAdapter.Targets t = OplusPluginDexKitAdapter.bindResolvedClasses(
                    single(sample, loader, "media-model"),
                    single(sample, loader, "lyric-model"),
                    model -> OplusPluginDexKitAdapter.bindArtwork(model,
                            single(sample, loader, "multi-icon"),
                            single(sample, loader, "static-icon"),
                            single(sample, loader, "normal-icon"),
                            single(sample, loader, "lottie-icon")),
                    true);
            return "OK artwork=" + (t.artwork != null ? "OK" : "FAIL " + simple(t.artworkFailure));
        });
        String legacy = outcome(() -> {
            OplusPluginDexKitAdapter.Targets t = OplusPluginDexKitAdapter.legacy(loader);
            return "OK artwork=" + (t.artwork != null ? "OK" : "FAIL " + simple(t.artworkFailure));
        });
        Class<?> lrv;
        try {
            lrv = loader.loadClass(LRV);
        } catch (ClassNotFoundException e) {
            lrv = null;
        }
        Map<String, Integer> hooks = lrv == null ? new HashMap<>() : recyclerHooks(lrv);
        boolean model = dexKit.startsWith("OK") || legacy.startsWith("OK");
        boolean surface = hooks.getOrDefault("draw", 0) > 0;
        row.put("core", model && surface ? "OK" : "FAIL model=" + model + " surfaceDraw=" + surface);
        row.put("media-model.dexkit", dexKit);
        row.put("media-model.legacy", legacy);
        row.put("lyrics-recycler", lrv == null ? "MISSING" : "present");
        if (lrv != null) {
            Class<?> recycler = lrv;
            row.put("lyrics-recycler.layout", outcome(() -> {
                OfficialLyricsRecyclerCompatibility.Binding b = OfficialLyricsRecyclerCompatibility.resolve(recycler);
                return b != null ? "OK " + b.layoutName : "runtime-dexkit (not statically covered)";
            }));
            row.put("lyrics-recycler.hooks", "draw=" + hooks.getOrDefault("draw", 0)
                    + " setLyrics=" + hooks.getOrDefault("dataset", 0)
                    + " current=" + hooks.getOrDefault("current", 0)
                    + " pivot=" + hooks.getOrDefault("pivot", 0)
                    + " rowStyle=" + hooks.getOrDefault("rowStyle", 0)
                    + " immersiveEntry=" + hooks.getOrDefault("immersive", 0));
        }
        row.put("lyric-position-controller", outcome(() -> {
            JSONArray hits = sample.getJSONObject("invokes").getJSONArray("lyric-position-controller");
            if (hits.length() != 1) return "none (" + hits.length() + " candidates)";
            JSONArray hit = hits.getJSONArray(0);
            Method m = loader.loadClass(binary(hit.getString(0)))
                    .getDeclaredMethod(hit.getString(1), Long.class, boolean.class);
            return Modifier.isStatic(m.getModifiers()) ? "FAIL static" : "OK";
        }));
        return row;
    }

    /** Mirrors the method loop in LockscreenLyricsModule.tryInstallLyricsRecyclerViewHook. */
    private static Map<String, Integer> recyclerHooks(Class<?> lrv) {
        Map<String, Integer> n = new HashMap<>();
        for (Class<?> current = lrv; current != null; current = current.getSuperclass()) {
            for (Method method : current.getDeclaredMethods()) {
                String key = null;
                if (n.getOrDefault("draw", 0) == 0 && "draw".equals(method.getName())
                        && method.getReturnType() == void.class
                        && method.getParameterTypes().length == 1
                        && method.getParameterTypes()[0] == Canvas.class) {
                    key = "draw";
                } else if ("setLyrics".equals(method.getName())
                        && method.getReturnType() == void.class
                        && method.getParameterTypes().length == 1
                        && List.class.isAssignableFrom(method.getParameterTypes()[0])) {
                    key = "dataset";
                } else if (LyricsRecyclerViews.isLyricsRecyclerCurrentLyricMethod(method)) {
                    key = "current";
                } else if (LyricsRecyclerViews.isLyricsRecyclerScalePivotMethod(method)) {
                    key = "pivot";
                } else if (OfficialLyricRowStyleMethodPolicy.matches(method, lrv)) {
                    key = "rowStyle";
                } else if (OfficialImmersiveLyricEntryPolicy.matches(method, lrv)) {
                    key = "immersive";
                }
                if (key != null) n.merge(key, 1, Integer::sum);
            }
        }
        return n;
    }

